// 🔴 **이 파일은 지금 `server.cpp` 가 원래 자리에서 `#include` 한다.**
//   그래서 전처리 결과가 이전과 **한 글자도 다르지 않고**, 산출물(`.o`)이 **0 차이**여야 한다.
//   그 대조가 "떼어 냈지만 아직 아무것도 안 바꿨다"를 **값으로** 증명한다.
//   (arduino 가 펌웨어 846줄을 이 방법으로 빼고 `hex` 0 을 얻었다. 서버도 같은 방법을 쓴다.)
//
// ⏳ **다음 단계에서 뒤집는다** — `main.cpp` 가 번역 단위가 되고 서버 조각들을 include 하는 쪽으로.
//   🔴 **그때부터 축이 생긴다.** 지금은 축이 없다는 것을 먼저 증명해 두는 것이 목적이다.
//
// ⚠ 그러므로 **이 파일을 단독으로 컴파일하지 마라.** 빌드는 여전히 `c++ … server.cpp` 다.
//
// ═══════════════════════════════════════════════════════════════════════════
// 🔴 **이 파일이 사용 샘플이다.** 여기만 고쳐서 자기 주차장을 만든다 (사용자 확정 2026-08-19)
//
// ── 빌드 ────────────────────────────────────────────────────────────────────
//   cd 조별과제샘플/server
//   c++ -std=c++11 -O2 -w -DBUILD_ID='"내판본"' -o server_test server.cpp
//
// ── 실행 ────────────────────────────────────────────────────────────────────
//   ./server_test --port-offset=300      # 🔴 **자기 시험은 오프셋을 줘라**
//                                        #    (안 주면 9991/9900/5500 을 잡는다)
//   포트는 세 개다 : 아두이노 9991+N · 화면(HTTP/WS) 9900+N · 폰 5500+N
//   ⚠ `--port-offset=400` 은 피해라 — 폰 포트가 5900 이 되어 macOS 화면공유와 부딪힌다
//
// ── 잘 됐는지 보는 법 ───────────────────────────────────────────────────────
//   ① 기동 로그 끝에  `= 조립 표 검사 — 자리 N개 · 문제 없음`
//   ② 브라우저로 `http://127.0.0.1:9900+N/`
//   ③ 🔴 **서버가 틀린 것을 말해 준다.** 자세한 문구와 뜻은
//      `docs/net/GUIDE-server-says.md` 에 있다 — **막지 않고 말만 한다**
//
// 🔑 **선언하지 않은 모듈은 꺼진 것이다.** 장치에 있어도 화면에 안 나오고,
//   서버는 그것을 `미결속모듈` 로 센다. **결함이 아니라 "안 쓰기로 한 것"이다.**
// ═══════════════════════════════════════════════════════════════════════════

int main(int argc, char** argv) {
    // 🔑 `WSAStartup`·`SIGPIPE`·`SIGINT/TERM` 은 **여기 없다.** 정적 초기화가 먼저 다 해 뒀다
    //   (`server.cpp` 의 `ProcessInit`). **Winsock 이 무엇인지 몰라도 주차장을 만들 수 있다.**
    int rc;
#include "cli.h"      // 손잡이 해석 — --log · --port-offset · --park-dev · 시험용 셋
    // --selftest 는 로그 파일을 열지 않는다. 자가검증 출력이 운영 로그에 섞이면
    // 인스턴스 경계 없이 사람이 만든 줄이 끼어드는 셈이라, 계약이 지키려는 것을 스스로 깬다.
    if (argc > 1 && std::string(argv[1]) == "--selftest") rc = selftest();
    else {
        open_log(log_path);

        // ── 🔴 여기가 **사용 코드**다 (REQ-0272) ─────────────────────────────
        //   사용자 요구: *"코드 작성 시점에 해당 코드의 **흐름이 보인다**"*
        //   위에서 아래로 읽으면 **무슨 일이 어떤 순서로** 일어나는지 보여야 한다.
        //
        //   ⚠ **자동 배선을 쓰지 않았다.** 자리마다 센서를 적는 것이 한 줄로 줄 수도 있지만
        //     그러면 **언제 무엇이 붙는지 안 보인다.** 배치는 호출자가 바꾸는 것이라 밖에 남긴다.
        //   🔑 판별자: **호출자가 바꿀 수 있으면 밖, 못 바꾸면 안.**

        // ═══════════════════════════════════════════════════════════════════
        // ① 주차장을 조립한다 — **여기만 고치면 된다**
        //
        // 🔴 **지금은 자리 하나만 켜져 있다.** 나머지는 아래에 주석으로 있다.
        //   *"모든 자리를 기본 비활성으로 두고 첫 자리만 활성화"* (사용자 확정 2026-08-19)
        //   ⚠ 선언하지 않은 모듈은 **꺼진 것**이다 — 장치에 있어도 화면에 안 나타난다.
        //     서버가 기동/등록 때 `미결속모듈` 로 그것을 **말해 준다**(정상이다. 겁먹지 마라).
        // ═══════════════════════════════════════════════════════════════════
        ParkingLot lot;

        // ── 켜져 있는 자리 하나 ──────────────────────────────────────────────
        //   `spot("A1")`            화면에 뜨는 **자리 이름**. 아무 문자열이나 된다
        //   `.sensor("P1", "A1")`   **P1 장치의 `A1` 모듈**을 이 자리에 붙인다
        //   센서를 둘 붙이는 이유: 하나가 죽어도 자리 판정이 산다(둘 중 하나라도 "찼다"면 찼다)
        //
        // 🔑 **이름이 자리 id 와 같을 필요가 없다.** 아래 둘은 우연히 같을 뿐이다 —
        //   `sensor("P1", "왼쪽센서")` 처럼 아무 이름이나 쓸 수 있다.
        //   (전에는 **모듈 이름이 자리 id 와 같아야만** 붙었고, 다르면 **아무 말 없이 안 붙었다.**
        //    `devid` 를 받게 되면서 그 암묵 규칙이 없어졌다.)
        lot.spot("A1").sensor("P1", "A1").sensor("P1", "B1");

        // ── 연습 ① 자리를 하나 더 켜려면 — 이 줄의 주석을 지운다 ────────────
        // lot.spot("A2").sensor("P1", "A2").sensor("P1", "B2");
        // lot.spot("A3").sensor("P1", "A3").sensor("P1", "B3");
        // lot.spot("A4").sensor("P1", "A4").sensor("P1", "B4");
        // lot.spot("A5").sensor("P1", "A5").sensor("P1", "B5");

        // ── 연습 ② 다른 사람의 아두이노를 붙이려면 ───────────────────────────
        //   `devid` 만 자기 것으로 바꾼다. 모듈 이름은 그 장치가 보내는 이름 그대로.
        // lot.spot("A6").sensor("KIM01", "왼쪽센서").sensor("KIM01", "오른쪽센서");
        //
        // ⚠ **`devid` 는 장치의 `client.ino` 에 있는 `#define DEVICE_ID` 다.**
        //   기본값 `"P1"` 을 안 바꾸면 **모두가 같은 id** 가 되고, 혼자 시험할 때는 멀쩡하다가
        //   **합치는 순간 서로 쫓아낸다.** 서버가 기동 때 그것도 말해 준다(`예시devid`).

        // ── 연습 ③ 입구·출구 차단봉을 켜려면 ─────────────────────────────────
        //   지금 칩의 `E1`·`X1` 은 **가상 차단봉**(시험용)이다 — 그래서 기본으로 꺼 뒀다.
        //   실물 차단봉을 달았을 때 아래 둘을 켠다.
        // lot.gate("E1", Gate::IN);                    // 입구 자리를 만들고
        // lot.spot("E1").actuator("P1", "E1");         // 그 자리에 차단봉 모듈을 붙인다
        // lot.gate("X1", Gate::OUT);
        // lot.spot("X1").actuator("P1", "X1");
        //
        // 🔑 `actuator` 는 **명령을 받는 모듈**이다(차단봉·표시등).
        //   `sensor` 와 갈라 두는 이유: **점유 판정에 섞이면 안 된다** —
        //   차단봉이 열렸다고 그 자리에 차가 있는 것이 아니다.

        // ② 서버에 싣는다
        ParkingServer srv(lot);

        // ═══════════════════════════════════════════════════════════════════
        // 🔴 **모듈에 명령 보내기** — `srv.send(devid, 모듈이름, 값)`
        //
        //   세 가지가 **같은 함수 하나**다. 다른 것은 **값의 뜻**뿐이다.
        //
        //     srv.send("P1", "LED1", 1);          // ① on/off      — 1=켬 0=끔
        //     srv.send("P1", "LCD1", 1234567);    // ② 7자리 숫자  — 그대로 표시
        //     srv.send("P1", "DOOR", 2);          // ③ 동작        — 아래 표대로
        //
        // 🔴🔴 **명령 작성 방법 — 이게 이 절의 핵심이다**
        //
        //   `값` 의 뜻을 **서버도 프로토콜도 모른다.** 그냥 32비트 정수를 실어 나른다.
        //   뜻을 정하는 것은 **기여자**이고, 정한 표를 **양쪽에 적어야 한다:**
        //
        //     여기(서버 호출부)  ─── 같은 표 ───  장치의 콜백(`client.ino`)
        //
        //   ⚠ **그 표가 어긋나면 조용히 다른 동작을 한다.** 오류도 안 뜬다 —
        //     서버는 `2` 를 보냈고 장치는 `2` 를 받았으니 **양쪽 다 성공이다.**
        //     🔑 **의미는 값으로 검증되지 않는다. 사람이 맞추는 수밖에 없다.**
        //
        //   ❌ 표 없이 `1,2,3,4` 만 쓰지 마라. 반년 뒤에 아무도 못 읽는다.
        //   ✅ 이렇게 적어라 — **그리고 장치 쪽 콜백 위에 같은 표를 복사해 둬라:**
        //
        //     // [DOOR 명령표]  (P1 / 모듈 "DOOR" · 정한 사람: 홍길동 2026-08-19)
        //     //   1 = 열기      2 = 닫기      3 = 잠금      4 = 잠금해제
        //     //   ⚠ 그 외 값은 장치가 `result=3`(수행 불가)로 답한다
        //     srv.send("P1", "DOOR", 1);   // 열기
        //
        //   장치 쪽(`client.ino`)은 이렇게 받는다 — **같은 표를 그 위에 적는다:**
        //
        //     // [DOOR 명령표]  1=열기 2=닫기 3=잠금 4=잠금해제   ← 위와 **똑같이**
        //     bool doorCmd(uint32_t arg) {
        //       if (arg == 1) { /* 열기 */ return true; }
        //       ...
        //       return false;              // 🔑 모르는 값은 **false** — 조용히 성공하지 마라
        //     }
        //     router.on("DOOR", doorCmd);  // setup() 에서 등록한다
        //
        // ⚠ **되돌아오는 답 읽는 법**
        //   `send()` 의 `true` 는 **"전선 큐에 넣었다"** 이지 "수행됐다"가 아니다.
        //   · 장치가 `result=0` 으로 ACK 하면 **콜백이 true 를 냈다**는 뜻
        //   · `result=3` 이면 **등록이 없거나 콜백이 false** 를 냈다는 뜻
        //   · 🔑 **실제로 그렇게 됐는지는 다음 상태 프레임의 에코가 답한다** — ACK 이 아니다
        //
        // ⚠ 값의 한계(실측): 프레임 최악 길이가 `G,999,255,4294967295,`+체크섬 = **23B**
        //   (한 줄 상한 64B). **7자리는 여유 있게 들어간다.** 값은 부호 없는 32비트까지.
        //
        // 🔑 **언제 부르나**: 지금 이 자리에서 부르면 **아직 장치가 안 붙어 있어 실패한다**
        //   (로그에 *"노드 `P1` 를 모른다"*). 실제로는 화면 명령이나 자기 조건에서 부른다.
        //   연습하려면 아래 ④ 루프 안에서 조건을 걸어 불러 봐라.
        // ═══════════════════════════════════════════════════════════════════

        // ③ 포트를 연다 — 아두이노 · 화면 · 폰
        if (!srv.openPorts()) return 1;

        // ④ 한 박자씩 돈다 — 수신 → 자리 판정 → 하행 송신 → 화면 방송
        while (srv.serveOneTick()) { }

        // ⑤ 요약을 남기고 닫는다
        srv.closeDown();
        rc = 0;
    }
    return rc;   // 🔑 `WSACleanup` 도 정적 소멸자가 한다

}
