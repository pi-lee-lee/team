// main.cpp — **개발자용 샘플.** 자기 주차장은 여기만 고쳐서 만든다.
//
// ── 빌드 ────────────────────────────────────────────────────────────────────
//   cd 조별과제샘플/server
//   c++ -std=c++11 -O2 -w -DBUILD_ID='"내판본"' -o server_test server.cpp
//
// ── 실행 ────────────────────────────────────────────────────────────────────
//   ./server_test --port-offset=300     🔴 자기 시험은 오프셋을 줘라
//   포트 셋 : 아두이노 9991+N · 화면 9900+N · 폰 5500+N
//   ⚠ `--port-offset=400` 은 피해라 — 폰 포트가 5900 이 되어 macOS 화면공유와 부딪힌다
//
// ── 잘 됐는지 보는 법 ───────────────────────────────────────────────────────
//   ① 기동 로그에  `= 조립 표 검사 — 자리 N개 · 문제 없음`
//   ② 브라우저로   http://127.0.0.1:(9900+N)/
//   ③ 🔴 틀린 것은 **서버가 말해 준다.** 문구와 뜻은 `docs/net/GUIDE-server-says.md`
//      **막지 않는다 — 말만 한다.** 서버가 안 뜨는 것은 포트 문제뿐이다
//
// ⚠ 이 파일은 단독으로 컴파일하지 마라. 빌드는 `c++ … server.cpp` 다.

int main(int argc, char** argv) {
    // `WSAStartup`·`SIGPIPE`·`SIGINT/TERM` 은 정적 초기화가 먼저 다 해 둔다.
    // 🔑 **Winsock 이 무엇인지 몰라도 주차장을 만들 수 있다.**
    int rc;
#include "cli.h"      // 손잡이 해석 — --log · --port-offset · --park-dev · 시험용 셋
    // `--selftest` 는 로그 파일을 열지 않는다 — 자가검증 출력이 운영 로그에 섞이면
    // 인스턴스 경계가 무의미해진다.
    if (argc > 1 && std::string(argv[1]) == "--selftest") rc = selftest();
    else {
        open_log(log_path);

        // ═══════════════════════════════════════════════════════════════════
        // ① 주차장을 조립한다 — **여기만 고치면 된다**
        //
        // 🔴 지금은 **자리 하나만 켜져 있다.** 나머지는 아래 주석에 있다.
        //   선언하지 않은 모듈은 **꺼진 것**이다. 장치에 있어도 화면에 안 나온다.
        //   서버는 그것을 `미결속모듈 N/M` 으로 센다 — **결함이 아니라 "안 쓰기로 한 것"** 이다.
        // ═══════════════════════════════════════════════════════════════════
        ParkingLot lot;

        //   `spot("A1")`          화면에 뜨는 **자리 이름**. 아무 문자열이나 된다
        //   `.sensor("P1","A1")`  **P1 장치의 `A1` 모듈**을 이 자리에 붙인다
        //   센서를 둘 붙이는 이유 : 하나가 죽어도 자리 판정이 산다
        //
        // 🔴🔴 **모듈 이름은 정확히 2글자다.** 장치의 표가 `char name[3]` 이라 전선에 2글자만 나간다.
        //   ⚠ 장치 쪽은 3글자 이상을 쓰면 **컴파일이 막는다.** 여기는 **안 막는다** —
        //     `"LED1"` 이라고 적으면 그냥 **아무 데도 안 붙고 아무 말도 없다.**
        //     🔑 서버는 `미결속모듈` 로 그것을 세지만, **이름을 미리 맞추는 것이 먼저다.**
        //
        // 🔑 **이름이 자리 id 와 같을 필요는 없다.** 아래는 우연히 같을 뿐이다 —
        //   `sensor("P1", "Q7")` 처럼 다른 이름이어도 붙는다(2글자만 지키면 된다).
        //
        //   `.actuator(...)` 는 **명령을 받는 모듈**이다. 한 자리에 센서와 같이 붙는다.
        //   🔑 액추에이터는 **점유 판정에서 빠진다** — 차단봉이 열렸다고 차가 있는 것이 아니다.
        lot.spot("A1")
           .sensor("P1", "A1")        // 주차확인센서
           .sensor("P1", "B1")        // 같은 자리의 둘째 센서(이중화)
           .actuator("P1", "LD")      // ① on/off      — 표시등
           .actuator("P1", "LC")      // ② 7자리 숫자  — 표시기
           .actuator("P1", "DR");     // ③ 동작 명령

        // ── 연습 ① 자리를 더 켜려면 — 주석을 지운다 ─────────────────────────
        // lot.spot("A2").sensor("P1", "A2").sensor("P1", "B2");
        // lot.spot("A3").sensor("P1", "A3").sensor("P1", "B3");
        // lot.spot("A4").sensor("P1", "A4").sensor("P1", "B4");
        // lot.spot("A5").sensor("P1", "A5").sensor("P1", "B5");

        // ── 연습 ② 다른 사람의 아두이노를 붙이려면 ──────────────────────────
        //   `devid` 만 자기 것으로 바꾼다. 모듈 이름은 그 장치가 보내는 이름 그대로.
        // lot.spot("A6").sensor("KIM01", "C1").sensor("KIM01", "C2");   // devid 는 1~8자
        //
        // ⚠ `devid` 는 장치의 `client.ino` 에 있는 `#define DEVICE_ID` 다.
        //   🔴 기본값 `"P1"` 을 안 바꾸면 **모두가 같은 id** 가 된다. 혼자 시험할 때는 멀쩡하다가
        //     **합치는 순간 서로 쫓아낸다.** 서버가 기동 때 그것도 말해 준다(`예시devid`).

        // ── 연습 ③ 차단봉을 켜려면 ──────────────────────────────────────────
        //   지금 칩의 `E1`·`X1` 은 **가상 차단봉(시험용)** 이라 꺼 뒀다.
        // lot.gate("E1", Gate::IN);
        // lot.spot("E1").actuator("P1", "E1");
        // lot.gate("X1", Gate::OUT);
        // lot.spot("X1").actuator("P1", "X1");
        //
        // 🔑 `actuator` 는 **명령을 받는 모듈**(차단봉·표시등)이다. `sensor` 와 갈라 둔다 —
        //   **점유 판정에 섞이면 안 된다.** 차단봉이 열렸다고 그 자리에 차가 있는 것이 아니다.

        // ② 서버에 싣는다
        ParkingServer srv(lot);

        // ═══════════════════════════════════════════════════════════════════
        // 🔴 모듈에 명령 보내기 — `srv.send(devid, 모듈이름, 값)`
        //
        //   셋이 **같은 함수 하나**다. 다른 것은 **값의 뜻**뿐이다.
        //     srv.send("P1", "LD", 1);          // on/off      — 1=켬 0=끔
        //     srv.send("P1", "LC", 1234567);    // 7자리 숫자  — 그대로 표시
        //     srv.send("P1", "DR", 2);          // 동작        — 아래 표대로
        //   ⚠ 이름 셋 다 **2글자**다. 장치 표(`client.ino`)의 이름과 **글자 그대로** 같아야 한다.
        //
        // 🔴🔴 **명령 작성 방법** — 값의 뜻을 **서버도 프로토콜도 모른다.**
        //   그냥 32비트 정수를 실어 나른다. 뜻을 정하는 것은 **기여자**이고,
        //   정한 표를 **양쪽에 똑같이** 적어야 한다:
        //
        //       여기(서버 호출부)  ─── 같은 표 ───  장치의 콜백(`client.ino`)
        //
        //   ⚠ **표가 어긋나면 조용히 다른 동작을 한다.** 오류도 안 뜬다 —
        //     서버는 `2` 를 보냈고 장치는 `2` 를 받았으니 **양쪽 다 성공이다.**
        //     🔑 **의미는 값으로 검증되지 않는다. 사람이 맞추는 수밖에 없다.**
        //
        //   ❌ 표 없이 `1,2,3,4` 만 쓰지 마라.
        //   ✅ 이렇게 적고 **장치 콜백 위에 같은 표를 복사해 둬라**:
        //
        //     // [DR 명령표]  (P1 / 모듈 "DR" · 정한 사람: 홍길동)
        //     //   1 = 열기   2 = 닫기   3 = 잠금   4 = 잠금해제
        //     //   ⚠ 그 외 값은 장치가 `result=3`(수행 불가)로 답한다
        //     srv.send("P1", "DR", 1);
        //
        //   장치 쪽(`client.ino`) — **같은 표를 그 위에 적는다**:
        //     // [DR 명령표]  1=열기 2=닫기 3=잠금 4=잠금해제   ← 위와 똑같이
        //     bool cmdDoor(uint32_t arg) {
        //       if (arg == 1) { /* 열기 */ return true; }
        //       return false;            // 🔑 모르는 값은 **false** — 조용히 성공하지 마라
        //     }
        //     router.on("DR", cmdDoor);   // setup() 에서 등록한다
        //
        // ⚠ **답 읽는 법**: `send()` 의 `true` 는 **"전선 큐에 넣었다"** 이지 "수행됐다"가 아니다.
        //     · 장치 ACK `result=0` → 콜백이 `true` 를 냈다
        //     · `result=3`          → 등록이 없거나 콜백이 `false` 를 냈다
        //     · 🔑 **실제로 그렇게 됐는지는 다음 상태 프레임의 에코가 답한다** — ACK 이 아니다
        //
        // ⚠ 값의 한계 : 프레임 최악 `G,999,255,4294967295,`+체크섬 = **23B**(한 줄 상한 64B).
        //   7자리는 여유 있게 들어간다. 값은 부호 없는 32비트까지.
        //
        // 🔑 **언제 부르나** : 여기서 바로 부르면 **아직 장치가 안 붙어 있어 실패한다.**
        //   실제로는 화면 명령이나 자기 조건에서 부른다. 연습하려면 아래 ④ 루프 안에서 조건을 걸어라.
        // ═══════════════════════════════════════════════════════════════════

        // ③ 포트를 연다 — 아두이노 · 화면 · 폰
        if (!srv.openPorts()) return 1;

        // ④ 한 박자씩 돈다 — 수신 → 자리 판정 → 하행 송신 → 화면 방송
        while (srv.serveOneTick()) {
            // ── 연습 ⑤ 왕복을 **눈으로** 보기 — 주석을 풀면 10초마다 표시등이 토글된다 ──
            //
            // 🔑 **왜 여기서 부르나** : 조립 시점(①②)에는 **장치가 아직 안 붙어 있다.**
            //   거기서 부르면 `send()` 가 `false` 를 내고 *"노드 `P1` 를 모른다"* 가 로그에 찍힌다.
            //   **도는 중**이어야 붙어 있다 — 그래서 루프 안이다.
            //
            // ⚠ 기본 샘플은 **아무것도 안 쏜다.** 켜는 것은 기여자의 선택이다.
            //
            // static long long last = 0;
            // static int on = 0;
            // if (now_ms() - last >= 10000) {        // now_ms() 는 단조 시계(ms)
            //     last = now_ms();
            //     on = !on;
            //     srv.send("P1", "LD", on);          // 🔑 표시등이 실제로 깜빡인다
            // }
            //
            // ✅ **이 예시는 주석을 풀면 경고 0 으로 빌드된다**(확인함).
            //   ⚠ 주석 안의 코드는 컴파일러가 안 본다 — **넣을 때 한 번 켜서 빌드해 봐야 한다.**
            //     안 하면 기여자가 푸는 순간 실패하고, **그 실패는 연습을 거기서 끝낸다.**
            //
            // 🔑 **결과가 눈에 보이는 것을 골라라.** 값만 보내고 아무 변화가 없으면
            //   "갔는지 안 갔는지"를 로그로만 판단하게 되고, 그건 연습이 아니다.
        }

        // ⑤ 요약을 남기고 닫는다
        srv.closeDown();
        rc = 0;
    }
    return rc;   // 🔑 `WSACleanup` 도 정적 소멸자가 한다
}

