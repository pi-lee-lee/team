// 심화 — **자리 판정을 직접 쓰기** (안 써도 된다)
//
// 🔑 **기본 판정으로 충분하면 이 절은 건너뛰어라.** 위의 `spot(...).sensor(...)` 만으로
//   자리는 정상 동작한다. 이건 *"판정 규칙을 내 것으로 바꾸고 싶을 때"* 만 본다.
//
// 기본 = **OR** — 아는 센서 중 하나라도 찼으면 찼다.
//   두 오류의 대가가 다르기 때문이다 : 빈 자리를 "찼다"고 하면 손해는 자리 하나이고,
//   **찬 자리를 "비었다"고 하면 운전자가 가서 못 댄다.**
//
// 바꾸려면 — `main()` **밖**에 두고 자리에 꽂는다:
//
//   struct 둘다찰때만 : SpotBehavior {
//       virtual bool occupied(const std::vector<SensorReading>& s) const {
//           int k = 0, v = 0;
//           for (size_t i = 0; i < s.size(); i++)
//               if (s[i].known) { k++; if (s[i].value) v++; }   // 모르는 센서는 안 센다
//           return k > 0 && v == k;
//       }
//   };
//   static 둘다찰때만 g_내판정;    // 🔴 서버보다 오래 살아야 한다(static/전역)
//
//   lot.spot("A1").sensor("P1","A1").sensor("P1","B1").behavior(g_내판정);
//
// ⚠ `SensorReading` 은 `known` 과 `value` 가 **따로다.**
//   `known == false` 는 *"아직 값을 못 받았다"* 이지 *"비었다"* 가 아니다.
//   🔴 둘을 한 `bool` 로 합치면 **모름이 거짓으로 무너진다.**
// ═════════════════════════════════════════════════════════════════════════════
