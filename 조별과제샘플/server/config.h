//   → ③ 은 **내 요약의 `왕복 최대 Nms(n=K)`** 가 창 B 에서 처음 값을 낸다(하행 송신→ACK 도착).
//     **그 값이 나오기 전까지 여유를 "확보됐다"고 말하지 않는다.**
//
// 192B 는 여전히 장치 64B 링버퍼의 **3배**라 `ssovf` 시험에 충분하고, 명령 28B 기준 **약 6~7건**을
// 한 거래에 싣는다. 넘치면 버리지 않고 **다음 창으로 미룬다** — 보수적으로 잡는 비용이 낮다.
