// ```
//   장치 송신 종료(최악)  = slotStart + due_max(400) + txTime_max(468)  = slotStart + 868
//        ⚠ txTime_max 는 185 가 아니다 — `waitForPrompt` 최대 300ms + 더미 채움 168ms 가
