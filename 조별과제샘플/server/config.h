// 🔴 **이 값은 "회선의 한계"가 아니다. "이론 최악을 덮는 값"이다** (arduino 검산):
// ```
//   이론 최악 : due 400 + txTime 468 = 868  → 여유 332ms → 192B(209ms) 를 고른 근거
//   실측      : due   0 + txTime  48 =  48  → 여유 1152ms → 192B 는 그 **18%**
// ```
// **약 20배 보수적이다.** 안전 설계를 최악으로 하는 것은 맞지만, **나중에 처리량이 부족해질 때
