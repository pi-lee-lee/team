//     20건이 몰렸다 — 경합과 반대 방향). **그래도 조건이 달랐다는 사실은 지운다고 없어지지 않는다.**
//
// ⚠ **말할 수 있는 것과 없는 것을 구분한다:**
//   · 말할 수 있다 — **2000ms 는 관측된 정상 분포를 자르지 않는다.**
//   · 말할 수 **없다** — 여유가 얼마인지. 로그 해상도가 1초라 `Δ=1s` 21건의 실제 경과는
//     (0,2)초 어딘가이고, **1.9초짜리 정상 송신이 있었을 가능성을 배제하지 못한다.**
