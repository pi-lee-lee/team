//   **"줄을 읽은 시점"** 이라 경합이 있으면 Δ 가 **실제보다 부풀려질 수 있다.**
//   → 즉 이 값은 **보수적인(=더 큰) 쪽으로 치우쳤을 수 있다.** 임계값 정하기에는 안전한 방향이다.
