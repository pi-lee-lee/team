//   `stuck` 이 `okto` 에 가깝다 → 기다려도 안 온다 → **T2 를 낮춰야** 한다(헛기다림)
//   ⚠ 기대치를 미리 박지 않는다 — §6.5-1 에서 옛 기대치와 견주다 데인 자리다.
