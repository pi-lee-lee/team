#pragma once
// ═════════════════════════════════════════════════════════════════════════
// Slots.h — 센서 값 · 수동 오버라이드
//   ⚙ 응용 성질 — 잠금 대상이 아니다
// ═════════════════════════════════════════════════════════════════════════
// 🔴🔴 **위치를 옮기지 마라.** `Config.h` 의 **정해진 자리에서** `#include` 된다.
//   헤더 순서가 바뀌면 선언·초기화 순서가 같이 바뀌어 **산출물이 달라진다.**

// ⚠ **`slot` 이라는 낱말이 이 저장소에서 셋을 가리킨다:**
//     `readSensor` · `sensorIndexOf`   → **모듈/센서 칸.** 인덱스가 전선의 `idx` 다
//     `slotName*` · `slotOverride*`               → **전선의 자리 토큰**(두 글자). 명세 용어다
//     `slotNo` · `slotStart` · `SLOT_MS`          → **1.2초 반송파 슬롯.** 시간이다
//   🔑 셋 다 `slot` 이었을 때는 코드를 읽어도 구분이 안 됐다.

// ─────────────────────────────────────────────────────────────────────────
// 🔴 **센서 수를 세는 상수가 없다.** 표를 훑어 `isSensor(i)` 로 고른다.
//
//   그래서 **센서를 표 앞쪽에 모을 필요가 없다** — 기여자가 `setup()` 에 적은 순서 그대로다.
//   🔑 옛 판은 `for (i = 0; i < SENSOR_N; i++)` 로 돌아서 "센서는 앞쪽 연속" 불변식을
//     요구했다. **그 불변식은 지키는 것이 아니라 그 루프가 만든 짐이었다.**
//   ⚠ `occ` 비트 위치는 **모듈 인덱스 그대로**다(액추에이터도 에코로 자기 비트를 갖는다).
//     그래서 비트가 겹치지 않는다 — 순서가 아니라 **누가 그 비트를 세우는가**가 가른다.
// ─────────────────────────────────────────────────────────────────────────

// 전선 ACK 이 되비추는 자리 토큰 두 글자 — 표의 이름이 그 값이다.
static inline char slotName0(uint8_t i) { return modName0(i); }
static inline char slotName1(uint8_t i) { return modName1(i); }

// 자리 토큰 두 글자 → 인덱스. 없으면 0xFF.
// 🔴 **센서만 찾는다** — 액추에이터 이름으로는 예약(R)·취소(C)를 걸 수 없고, 그것이 옳다.
static uint8_t sensorIndexOf(char c0, char c1) {
  for (uint8_t i = 0; i < MODULE_N; i++)
    if (isSensor(i) && modName0(i) == c0 && modName1(i) == c1) return i;
  return 0xFF;
}

// ═════════════════════════════════════════════════════════════════════════
// 🔓 **센서 읽기 함수** — 기여자가 자기 센서를 붙이는 자리
//
//   모양 :  `bool 이름()`   — 반환 **true = 찼다** · false = 비었다
//   등록 :  `node.sensor("A1").on(내함수);`
//   🔑 **명령 쪽과 같은 `on` 이다.** 한 번만 배우면 양쪽에 쓴다.
//
// 🔴 **문턱 판정은 핸들러가 한다.** 초음파는 거리(숫자)를 내는데 자리 상태는 참/거짓이다 —
//   *"몇 cm 아래면 찼다고 볼 것인가"* 는 **장치를 단 사람만 안다.**
//   ⚠ 이 자리를 비워 두면 그 판정이 서버나 화면으로 새어 나가 **두 곳에 생긴다.**
//
// 🔓 **핀 모드는 `setup()` 에서 네가 잡는다** — `pinMode(9, INPUT_PULLUP);` 같은 아두이노 기본이다.
//   🔑 그래서 핀이 하나든 둘이든(초음파 trig/echo) **등록 모양이 같다.**
//
// ⚠ **이 함수는 매 `loop()` 마다 불린다.** 오래 걸리는 측정을 그대로 넣으면 슬롯이 밀린다 —
//   `pulseIn` 은 최악 타임아웃만큼 **블로킹**한다. **간격을 두고 값을 캐시해라.**
// ═════════════════════════════════════════════════════════════════════════

// 🔴 `ParkingNode` — **상태를 한 캡슐로**
//   ⚠ **생성자를 두지 않는다.** AVR 전역 객체의 생성자는 `main()` 전에 돌고, NSDMI(`= 0`)를 쓰면
//   **`.bss` 영타 대신 생성자 코드가 생긴다.** 전역은 0 으로 시작하므로 아무것도 안 쓰는 것이 싸다.
// ═════════════════════════════════════════════════════════════════════════
class ParkingNode {
 public:
  // 🔴 **시작과 한 박자 — 정의는 `Runtime.h`** 다(이 파일보다 뒤에 온다).
  //   `begin()` 은 `espInit()` 을, `tick()` 은 `espRead()` 를 부르고 그 함수들이 뒤에 정의된다.
  void begin();
  void tick();

  // 🔓 **모듈 등록** — `setup()` 에서 부른다. 정의는 `Runtime.h`.
  //   ⚠ **호출 순서가 전선 `idx` 이고 `occ` 비트 위치다.** 센서·액추에이터를 섞어도 된다.
  ModRef sensor  (const char (&name)[3]);
  ModRef actuator(const char (&name)[3]);

  // 배너를 첫 `tick()` 에서 한 번만 찍기 위한 표시.
  // 🔴 **왜 `begin()` 이 아니라 첫 `tick()` 인가**: 배너의 `[SENS]` 줄이 **기여자가 등록한 것**을
  //   보고 값을 가른다. `begin()` 에서 찍으면 등록 전이라 **거짓말을 한다.**
  bool bannerDone;

  // 🔴 `begin()` 이 불렸나. **`slotStart == 0` 으로 판정하면 안 된다** —
  //   `begin()` 이 `slotStart = millis()` 를 세우는데 **부팅 직후 `millis()` 가 0** 이라
  //   세워도 0 이고, 그러면 "안 불렀다" 와 구별이 안 된다(실제로 거짓 경보가 났다).
  //   🔑 §"`0` 이 건강인지 못 셈인지" — **`0` 이 두 뜻을 겸하면 별도 플래그를 둔다.**
  bool beginDone;

  // 센서를 한 번 훑어 점유 비트를 갱신한다
  void readSensors() {
    uint16_t m = 0;
    for (uint8_t i = 0; i < MODULE_N; i++)
      if (isSensor(i) && readSensor(i)) m |= (uint16_t)1 << i;
    occMask = m;
  }

  uint16_t occMask;   // 점유 비트 (센서가 주인)
  uint16_t resMask;   // 예약 비트 (서버가 주인 — R 로 켜고 C 로만 끈다)

  // 🔓 **등록된 함수가 답이다.** 없으면 0 — 장치는 가짜 점유를 만들지 않는다.
  //   🔴 극성(HIGH/LOW)·문턱·필터는 전부 그 함수 안의 일이다. 센서마다 다르므로
  //     여기에 기본값을 두면 반은 틀린다. **틀린 기본값보다 없는 것이 낫다.**
  uint8_t readRealSensor(uint8_t i) {
    // ① 값을 내는 센서 — 문턱은 `.near(cm)` 이 정한다
    SensorValueFn vf = valOf(i);
    if (vf) {
      const long v = vf();
      // 🔓 전선에 실을 값. **hex 3자리(0~4095)로 확정됐으므로 `uint16_t` 로 충분하다** —
      //   `long`(4B)으로 두면 모듈당 2B 를 헛되게 쓴다(8모듈 16B).
      lastVal[i] = (v < 0 || v > 4095L) ? VAL_NONE : (uint16_t)v;
      // 🔴 **못 쟀다 ≠ 0cm ≠ 비었다.** 셋이 다른 진술이다.
      //   히스테리시스는 **값이 있을 때만** 작동한다 — 이 갈래는 값이 없어서 그 밖이다.
      //   실측 23.2% 가 못 쟀고 그중 **간헐(1~2슬롯)이 16/18** 이었다 → 참는다.
      if (v == SENSOR_NO_READING) {
        // 🔴🔴 **슬롯당 한 번만 센다.** `readSensors()` 는 **매 `loop()`** 돌기 때문에
        //   그냥 `noRead[i]++` 하면 **슬롯당 수백~수천 번** 올라 `N` 을 즉시 넘긴다.
        //   → 그러면 유지가 **사실상 없다.**
        //   🔑 monitor 가 실측으로 잡았다(2026-08-20 22:5x): 해제 직전 연속 빈칸 `V` 가
        //     **76%(16/21)가 1개**였다. `N=3` 이면 3 이상이어야 한다.
        //   ⚠ **그 증거가 이미 `[USD]` 의 `n65535` 포화에 있었다** — 같은 원인(매 루프 호출)인데
        //     나는 그것을 "이름이 틀렸다"로만 처리하고 **같은 검사를 여기 안 돌렸다.**
        //   ⚠ 그리고 내 시험 7개가 다 통과했다 — `readSensor` 를 **1회씩 직접** 불렀기 때문이다
        //     (§"시험 경로 ≠ 실기 경로"). 시험도 매 루프를 밟게 고쳤다.
        //   ⚠ `slotNo` 는 `TxState.h` 에 있고 그 파일은 **이 파일보다 뒤**다(`Config.h:94` 에서
        //     `Slots.h` 가 들어온다). 그래서 **시간으로 슬롯을 센다** — `SLOT_MS` 는 앞(83행)이다.
        //   🔑 실제 슬롯 경계와 **위상이 다를 수 있다**(그것은 `slotStart` 기반이다).
        //     그래도 목적은 달성된다 — 필요한 것은 *"1.2초마다 한 번"* 이지 *"슬롯과 정렬"* 이 아니다.
        const uint8_t sl = (uint8_t)(millis() / SLOT_MS);
        // 🔴 `noRead[i] == 0` 을 같이 본다 — `noReadSlot` 초기값 0 이 **첫 슬롯 번호 0 과 겹쳐**
        //   첫 회를 안 세는 결함이 있었다(시험이 3슬롯에서 2 를 세어 FAIL 했다).
        //   ⚠ 부팅 직후·값이 온 뒤에는 둘 다 0 이라 그 겹침이 **반드시** 일어난다.
        if (noRead[i] == 0 || noReadSlot[i] != sl) {
          noReadSlot[i] = sl;
          if (noRead[i] < 255) noRead[i]++;
        }
        if (noRead[i] >= NO_READ_RELEASE_N) return 0;   // 연속 N**슬롯** → **해제**
        return (uint8_t)((occMask >> i) & 1);           // 그 전엔 **직전 상태 유지**
      }
      noRead[i] = 0;
      const uint16_t th = nearOf(i);
      if (th == 0) return 0;                 // 🔴 문턱이 없으면 **판정 안 한다**(값만 보낸다)
      // 🔴🔴 **히스테리시스** — 문턱 하나로는 진동을 못 막는다(실측: 폭 70/32/23cm 가
      //   문턱 60 을 넘나들어 **1초 간격 전이**가 났다). 들어올 때와 나갈 때를 갈라 놓으면
      //   **진동이 구조적으로 불가능해진다** — §"조건이 성립할 수밖에 없게 만들어라".
      //   🔑 상태는 `occMask` 에 이미 있다 → **RAM 추가 0**
      if ((occMask >> i) & 1) return (v < (long)(th + NEAR_RELEASE_CM)) ? 1 : 0;  // 찼던 상태
      return (v < (long)th) ? 1 : 0;                                              // 비었던 상태
    }
    // ② true/false 를 직접 내는 센서 — 옛 계약 그대로
    SensorFn f = senseOf(i);
    return f ? (f() ? 1 : 0) : 0;
  }

  // ── 🔓 센서가 낸 값 ─────────────────────────────────────────────────────
  //   전선 형식은 **서버 명세가 정한다**(hex 3자리 = 0~4095 확정 · 필드 위치는 명세 대기).
  //   여기서는 값만 들고 있는다 — 프레임 조립은 `FrameCodec` 의 일이다.
  // 🔴 `VAL_NONE` 은 **"못 쟀다"** 다. hex 3자리로는 표현할 수 없는 값을 골랐다.
  static const uint16_t VAL_NONE = 0xFFFF;
  uint16_t lastVal[MODULE_CAP];
  // 🔴 연속 "못 쟀다" 횟수. `NO_READ_RELEASE_N` 회를 넘으면 해제한다.
  //   ⚠ 값이 오면 **0 으로 되돌린다** — 안 되돌리면 누적돼 언젠가 무조건 해제된다.
  uint8_t noRead[MODULE_CAP];
  // 🔑 `noRead` 를 **슬롯당 한 번만** 올리려고 마지막으로 센 슬롯을 기억한다.
  //   ⚠ `slotNo` 하위 바이트만 쓴다 — 256슬롯(5분)마다 겹치지만 **연속 3 을 보는 데는
  //     문제없다**(겹치려면 그 사이 값이 한 번도 안 와야 한다).
  uint8_t noReadSlot[MODULE_CAP];



  // ─────────────────────────────────────────────────────────────────────────
  // 수동 오버라이드 — 칸별. 실제 센서값보다 **우선**한다.
  //   차 없이 화면·서버를 시험할 수단이고, 전선의 `T` 프레임이 이 함수들을 부른다.
  // ─────────────────────────────────────────────────────────────────────────
  uint16_t ovrActive;   // 비트 i = 이 칸에 값을 강제하고 있다  ( = S 프레임의 tmask)
  uint16_t ovrValue;    // 비트 i = 강제할 값 (ovrActive 가 1 일 때만 의미 있다)

  // 테스트 모드 무장 여부. 무장 중일 때만 칸별 주입(`T,...,S,..`)이 먹는다.
  // **재부팅하면 해제 상태로 시작한다** — 가짜 값이 되살아나는 것이 더 위험하다.
  bool testArmed;

  void slotOverrideSet(uint8_t i, uint8_t value) {
    if (!isSensor(i)) return;
    uint16_t bit = (uint16_t)1 << i;
    ovrActive |= bit;
    if (value) ovrValue |= bit; else ovrValue &= (uint16_t)~bit;
  }

  void slotOverrideClear(uint8_t i) {
    if (!isSensor(i)) return;
    uint16_t bit = (uint16_t)1 << i;
    ovrActive &= (uint16_t)~bit;
    ovrValue  &= (uint16_t)~bit;
  }

  void slotOverrideClearAll(void) {
    ovrActive = 0;
    ovrValue  = 0;
  }

  // ★ 센서값의 단일 진입점 ★
  //   우선순위: 수동 오버라이드 > 실제 센서
  uint8_t readSensor(uint8_t i) {
    // 무장 중일 때만 주입이 적용된다 — 해제 상태에서 주입값이 실리면 **tmask 가 안 붙은 채로**
    // 전선에 나가고 서버·화면이 그것을 실측으로 믿는다. 여기서 막으면 "해제 = 현실로 복귀"가
    // 호출 순서에 기대지 않고 **구조적으로** 성립한다.
    if (testArmed && (ovrActive & ((uint16_t)1 << i))) return (uint8_t)((ovrValue >> i) & 1);

    // 실제 센서는 **무장 중에도 계속 읽는다.** 그건 진실이고 가릴 이유가 없다.
    //   🔴 함수를 안 붙인 센서는 늘 0(비었다)이다 — 부팅의 `[SENS]` 줄이 그것을 지목한다.
    return readRealSensor(i);
  }

};

static ParkingNode node;
