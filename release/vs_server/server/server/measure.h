// measure.h — **판정 수치를 기여자가 선언하고 서버가 장치에 내려보낸다**
// ═══════════════════════════════════════════════════════════════════════════
// 계약 정본 : docs/net/SPEC-sensor-value.md §15.4
//
// 사용자 요구:
//   *"서버에서는 실시간 수치를 받지 않는다. 다만 **아두이노가 사용할 수치를 보내거나
//   수정할 수 있도록** 바꾸는게 좋을거 같다."*
//
// 🔑 **무엇이 바뀌나** — 판정 수치를 고치는 비용이다:
//   ```
//   전 : client.ino 의 상수를 고친다  → 🔴 고칠 때마다 **굽기**(리셋이 관측 창을 끊는다)
//   후 : lot.measure(...) 를 고친다   → ✅ **굽기 0회 · 서버 재기동뿐**
//   ```
//   근거는 값이다 — 굽기의 절반 이상이 **수치 조정 하나** 때문에 일어난다.
//
// 🔴 **장치에 저장하지 않는다.** 매 등록 때 서버가 내려보낸다.
//   런타임 저장은 **낡은 값이 남는다**(같은 날 안드로이드 `server.properties` 가 그 사고였다).
//   저장 안 하면 낡은 값이 **원리적으로** 안 남는다 — 서버 소스가 정본이다.
//
// ⚠ **선언 안 하면 `K` 를 안 보낸다.** 그러면 장치의 컴파일 기본값이 산다.
//   🔑 *"서버가 늘 이긴다"* 가 아니라 *"서버가 말하면 이긴다"* 다 —
//   안 그러면 기여자가 한 줄 안 썼다고 문턱이 0 이 된다.
// ═══════════════════════════════════════════════════════════════════════════
#ifndef MEASURE_H
#define MEASURE_H

#include <string>

// 🔴 전선 폭이 정한 상한 — `K` 의 각 칸은 **hex 3자리**다(§15.4).
//   `V`/`E` 의 값 규약을 그대로 빌려 쓴다. 새로 정하면 두 규칙이 생긴다.
static const long MEASURE_MAX = 4095;

// 모듈 하나의 판정 수치 선언.
struct MeasureDecl {
    std::string devid;
    std::string name;      // 모듈 이름(2바이트)
    // 🔑 셋 다 **-1 = 안 정했다**. `0` 이 아니다 — `0` 은 "문턱 0cm" 라는 뜻이 될 수 있다.
    //   ⚠ 하나라도 -1 이면 `K` 를 **안 보낸다**(§15.4.1) — 반쪽만 내려보내면
    //     장치가 절반은 서버 값, 절반은 자기 기본값으로 판정하게 되고 그건 아무도 못 재현한다.
    // 🔴🔴 **단위가 없다.** `E` 의 `v` 와 **같은 눈금**일 뿐이다 —
    //   장치가 `v` 를 이 값과 비교한다. 그 눈금을 정하는 것은 **기여자의 센서 함수**이고 계약이 아니다.
    //   ⚠ 이름의 `_cm` 은 **지금 샘플이 cm 를 쓰기 때문**이지 계약이 cm 라는 뜻이 아니다.
    long near_cm;          // 이 값 **이하**면 찼다
    long far_cm;           // 이 값 **초과**면 비었다  (near < far · 히스테리시스)
    // 🔴🔴 **`min` 은 성능 손잡이가 아니다 — 센서의 물리 배치에 딸려 있다** (arduino 지적).
    //   그 센서가 물리적으로 잴 수 있는 하한이다(반향이 겹치는 거리).
    //   ★ **배치를 모르면 바꾸지 마라.** 바꿀 근거는 코드가 아니라 **자를 대 본 사람**에게 있다.
    //   ⚠ 안 적으면 다음 사람이 이것을 손잡이로 읽는다 — `US_NEAR_CM` 이 그렇게 물린다.
    long min_cm;           // 이 값 **미만은 "못 쟀다"** 이지 "가깝다" 가 아니다

    MeasureDecl() : near_cm(-1), far_cm(-1), min_cm(-1) {}

    // 🔑 **셋이 다 있고 범위 안이고 순서가 맞나.** 하나라도 아니면 안 보낸다.
    //   ⚠ 판정을 여기 한 곳에 둔다 — 보내는 쪽과 검사하는 쪽이 갈리면 관대한 쪽이 이긴다.
    bool complete() const {
        if (near_cm < 0 || far_cm < 0 || min_cm < 0) return false;
        if (near_cm > MEASURE_MAX || far_cm > MEASURE_MAX || min_cm > MEASURE_MAX) return false;
        // 🔴 `near < far` 가 히스테리시스의 정의다. 뒤집히면 **찼다와 비었다가 겹치거나 빈다.**
        if (!(near_cm < far_cm)) return false;
        // 🔑 `min` 이 `near` 보다 크면 **문턱에 영영 못 닿는다** — 판정이 조용히 죽는다.
        if (min_cm >= near_cm) return false;
        return true;
    }
    // 🔑 **왜 불완전한지**를 사람 말로. 기동 로그가 이것을 그대로 찍는다 —
    //   `false` 만 돌려주면 기여자는 무엇을 고쳐야 하는지 모른다.
    std::string why_incomplete() const {
        if (near_cm < 0 || far_cm < 0 || min_cm < 0)
            return "near/far/min 셋을 다 정해야 한다(하나라도 빠지면 안 보낸다)";
        if (near_cm > MEASURE_MAX || far_cm > MEASURE_MAX || min_cm > MEASURE_MAX)
            return "값이 0~4095 밖이다(전선이 hex 3자리다)";
        if (!(near_cm < far_cm))
            return "near < far 여야 한다(히스테리시스). 지금은 찼다/비었다가 겹치거나 빈다";
        if (min_cm >= near_cm)
            return "min < near 여야 한다. 지금은 문턱에 영영 못 닿아 판정이 죽는다";
        return "";
    }
};

#endif // MEASURE_H
