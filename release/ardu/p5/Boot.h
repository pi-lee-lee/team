// Boot.h — 부팅 원인 기록(MCUSR 미러)   ⚙
// ⚠ 스케치(pN.ino)의 프레임워크 블록에서 include 된다 — 자리·순서 고정(hex 가 바뀐다) · 📖 docs/arduino/LEDGER.md
// ─────────────────────────────────────────────────────────────────────────
// 부팅 원인 기록 — 재부팅 이유를 로그로 가르는 유일한 수단이다
//
// MCUSR 은 리셋 원인 비트를 들고 있지만 **부트로더가 지우고 갈 수 있다.** 그래서 앱 코드가
// 아니라 `.init3`(스택은 잡혔고 .data/.bss 초기화 전)에서 가장 먼저 복사한다.
// 복사본은 `.noinit` 에 둔다 — 일반 전역이면 그 뒤 .bss 초기화가 0 으로 덮어쓴다.
//
// 🔴 **이 보드(optiboot 4.4)는 MCUSR 을 0 으로 지우고 넘어온다** — 그래서 MCUSR 을 직접 읽으면 늘 0 이다.
//   ★ 다만 optiboot 4.4+ 는 지우기 **전** 값을 **r2** 에 남긴다. MCUSR 이 0 이면 r2 를 읽는다.
//   r2 는 crt 초기화가 건드리지 않는 call-saved 레지스터라 .init3 에서도 살아 있다.
//   그래도 0 이면 "원인 없음"이 아니라 **"불명"** 으로 찍는다 — 없는 정보를 있는 것처럼 말하지 않는다.
//   ⚠ 이 계측이 사는지는 굽고 나서 **리셋 버튼(EXTRF)과 전원 재인가(PORF)가 다른 답을 내는 것**으로 확인한다.
//
// `wdt_disable()` 도 여기서 한다. 워치독 리셋으로 들어왔다면 WDT 가 짧은 주기로 켜진 채
// 남아 있을 수 있고, 그대로 두면 부팅을 마치기 전에 또 리셋된다(벽돌 루프).
// ─────────────────────────────────────────────────────────────────────────
uint8_t mcusrMirror __attribute__((section(".noinit")));
void earlyInitCapture(void) __attribute__((naked, used, section(".init3")));
void earlyInitCapture(void) {
  uint8_t m = MCUSR;                     // 부트로더가 안 지웠으면 여기 있다
  MCUSR = 0;
  if (m == 0) __asm__ __volatile__ ("mov %0, r2" : "=r" (m));   // optiboot 4.4+: 지우기 전 값이 r2 에 있다
  mcusrMirror = m;
  wdt_disable();
}

// ── 6단: AVR 워치독 — **기본값 꺼짐. 이유를 읽고 나서 켜라.** ──────────────────
// 고치는 것 : **아두이노 자신이 행(hang)에 빠진 경우만**이다.
// 🔴 못 고치는 것 : **ESP 다.** AVR 리셋은 ESP 를 리셋하지 않는다(전원도 RST 도 그대로다).
//
// 위험은 실재한다: WDT 를 안전하게 처리하지 못하는 옛 부트로더(ATmegaBOOT 계열)에서는
//   워치독 리셋이 **앱으로 넘어가기 전에 또 리셋을 걸어** 무한 리셋이 된다.
//   ISP 프로그래머 없이 되돌릴 수 없다 — 즉 보드가 죽는다.
// 이 보드 : optiboot 는 WDT 안전이다. 115200 업로드 성공이 그 정황이지만 **확인된 것은 아니다.**
//   낮은 기대효과와 벽돌 위험을 맞바꾸지 않는다.
//
// 켜기 전 확인 절차 — 🔴 **예비 보드로 해라**:
//   1) 1 로 바꿔 굽고 정상 부팅·`[BOOT]` 줄을 본다
//   2) `loop()` 를 9초 막아 리셋되는지, **그 뒤 정상 부팅하는지** 본다
//   2)에서 안 올라오면 ISP 가 필요하다.
#define ENABLE_WDT 0

