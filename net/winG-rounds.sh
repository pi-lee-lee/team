#!/bin/sh
# 창 기준선 주입 — 라운드 반복 감독기 (루트 요청 · 2026-08-18 작성 · 2026-08-19 개정)
#
# 🔴 **정지 조건을 끄지 않는다.** 장치가 오프라인이면 각 주입기는 규칙대로 멈추고,
#    이 감독기가 잠깐 쉬었다가 **새 라운드**를 연다.
#    ⚠ 조건을 완화해 계속 돌리면 **죽은 장치에 계속 넣게 된다** — 그래서 재시작 쪽을 골랐다.
#    (조건을 지키면서 부하를 이어 가는 방법이 조건을 무르게 하는 것보다 낫다)
#
# ⚠ 라운드 수는 **유한하다.** 감시 없는 무한 루프를 만들지 않는다.
#
# ── 🔴 2026-08-19 개정 셋. **부하 인자는 한 글자도 안 바꿨다** (대조군이 깨지므로)
#
#  (1) 로그 파일명의 날짜가 `2026-08-18` 로 **박혀 있었다.** 창 M 자료가 그 이름으로 남았다.
#      → 오늘 날짜를 쓴다. 세 번째 인자로 덮어쓸 수 있다(자정을 넘겨 이어 돌릴 때).
#
#  (2) **정지선을 감독기가 실제로 본다.** 요청서에만 적힌 정지선은 안 지켜진다 —
#      2026-08-18 에 조건이 21:00:37 에 충족됐는데 주입이 21:03:14 까지 130건 더 돌았다.
#      🔴 다만 판정 지표(`>=64B` 표본 수)는 **monitor 의 계측기에 있고 나는 못 본다.**
#      **못 보는 것을 조건으로 적지 않는다**(CLAUDE.md). 대신 **내가 볼 수 있는 신호**를 본다:
#        `.team/STOP-<TAG>` 파일이 생기면 멈춘다. 계수를 가진 쪽(monitor)이 그것을 만든다.
#      🔑 파생 값은 원본을 가진 쪽이 계산한다 — 내가 짐작해서 세지 않는다.
#
#  (3) **시간 상한.** 신호가 영영 안 오는 경우를 위한 바닥이다. 이게 없으면 (2)가
#      "아무도 안 누르면 끝까지 돈다"가 된다. 상한에 걸려 끝나면 **"미달"로 보고해야 한다.**
#
# ⚠ (2)(3)은 **끝나는 시점**을 바꾼다. 창 M 에는 없던 장치다 —
#   실제로 발동했으면 보고에 적어라. 발동하지 않았으면 창 M 과 같은 규약으로 끝난 것이다.

ROUNDS=${1:-8}
# 🔑 **회차 표는 부하 인자가 아니다.** 라운드·인스턴스·건수·간격은 절대 바꾸지 않되,
#    rid 접두와 기록 파일은 창마다 갈라야 한다 — 안 그러면 append-only 로그에서 짝이 섞인다.
TAG=${2:-G}
DATE=${3:-$(date '+%Y-%m-%d')}
LOG=net/inject-win${TAG}-${DATE}.log
STOP=.team/STOP-${TAG}
MAX_MIN=${MAX_MIN:-40}

T0=$(date '+%s')
echo "$(date '+%Y-%m-%d %H:%M:%S')  감독기 시작 — 라운드 $ROUNDS · 태그 $TAG · 정지신호 $STOP · 상한 ${MAX_MIN}분" >> "$LOG"

stop_reason=""
r=1
while [ "$r" -le "$ROUNDS" ]; do
  # 🔴 라운드를 열기 **전에** 두 조건을 본다. 라운드 중간에는 못 멈춘다(주입기가 자기 규칙으로 돈다) —
  #    그래서 정지 지연의 상한은 **한 라운드**다. 창 M 기준 약 3분. 그 사실을 보고에 적어라.
  if [ -f "$STOP" ]; then stop_reason="정지신호($STOP)"; break; fi
  elapsed_min=$(( ( $(date '+%s') - T0 ) / 60 ))
  if [ "$elapsed_min" -ge "$MAX_MIN" ]; then stop_reason="시간상한(${MAX_MIN}분) — 🔴 미달로 보고할 것"; break; fi

  echo "$(date '+%Y-%m-%d %H:%M:%S')  라운드 $r/$ROUNDS 시작" >> "$LOG"
  i=1
  for S in A1 A2 A3 A4 A5 B1 B2 B3; do
    python3 net/downlink_inject.py --port 9900 --allow-production --slot "$S" \
      --interval 0.3 --start-delay 0 --count 60 --rid-prefix "inj${TAG}${r}-$i" \
      --stop-queue-full 20 --log "$LOG" > /dev/null 2>&1 &
    i=$((i + 1))
  done
  wait
  echo "$(date '+%Y-%m-%d %H:%M:%S')  라운드 $r 종료" >> "$LOG"
  sleep 5
  r=$((r + 1))
done

if [ -n "$stop_reason" ]; then
  echo "$(date '+%Y-%m-%d %H:%M:%S')  🔴 조기 종료 — $stop_reason (라운드 $r/$ROUNDS 에서 멈춤)" >> "$LOG"
fi
echo "$(date '+%Y-%m-%d %H:%M:%S')  창 ${TAG} 주입 전체 종료" >> "$LOG"
