#!/usr/bin/env python3
"""`0` 을 낼 때 **분모와 표지를 같이 찍는다** — monitor 도구 전체의 출력 규약.

왜 (루트 제안 2026-08-17 08:1x · 오늘 같은 형태로 **네 번째** 사고 뒤)
  `0` 은 우리 시스템에서 **가장 위험한 출력값**이다. 뜻이 셋인데(원장 1.1)
  화면에는 똑같이 `0` 으로 나온다:

    ① 건강   — 정말 안 났다
    ② 미실행 — 그 일이 한 번도 안 돌았다
    ③ 못 셈  — **표지가 틀렸거나 파서가 그 줄에 도달하지 못했다**

  오늘 ③이 네 번 나왔다:
    · `ack_timeout` 을 `미주입` 으로 이름 붙여 도달 실패가 분모에서 빠짐
    · 요약기 `drop` 칸을 펌웨어 `[CNT] drop=` 으로 오독(가설 하나가 죽었다)
    · `★ 정지 감지 0` 을 "C 수정됨" 으로 읽음 — 실은 경로가 실행조차 안 됨
    · `garbage_lead.py` 가 표지 셋을 틀려 세 번 연속 `0건`

  **네 번 다 "무엇을 찾았고 몇 줄을 훑었나" 가 같이 찍혔으면 즉시 보였다.**

규약
----
    0 이 아닐 때 : `표지 12건`
    0 일 때      : `표지 0건  ⚠ [훑은 줄 94,860 · 찾은 것 "★ 정지 감지"]`
                   → 분모가 0 이면 **"못 셈"** 이 먼저 의심된다
                   → 분모가 큰데 0 이면 **표지가 틀렸는지** 먼저 본다

⚠ 이 도구는 `0` 의 뜻을 **정해 주지 않는다.** 셋 중 무엇인지 가르는 것은 사람이다.
   이것이 하는 일은 **가를 수 있는 정보를 화면에 같이 올리는 것**뿐이다.

────────────────────────────────────────────────────────────────────────
왜 문장이 아니라 형식인가 (이 파일이 존재하는 이유)
────────────────────────────────────────────────────────────────────────
  오늘 같은 종류의 사고가 **여섯 번** 났고, 그때마다 원장에 *"조심하라 · 정의를 맞춰라"* 를
  적었다. **그 지식으로 다음 사고가 안 막혔다** — 원장 §1.1 을 써 놓은 사람이 §1.1 에 네 번 걸렸다.

  막은 것은 지식이 아니라 **출력 형식**이었다. STATUS 표에 "찾은 문자열" 칸을 넣자마자
  `banner 1` 이 **Uno 배너**라는 것이 보였고, 요약기가 **밤새 기전 B 를 한 번도 안 세고
  있었다**는 것이 드러났다. 그 전까지 아무도 이상을 못 느꼈다.

      ### 규칙이 아니라 출력 형식이라 안 지키면 눈에 띈다.

  **문장은 읽어야 작동하고, 형식은 안 읽어도 작동한다.**

  `calib()` 도 같은 성질이다. `garbage_lead.py` 는 표지를 **셋 연달아** 틀렸는데
  (Uno/ESP 배너 혼동 · 로그가 이스케이프 텍스트인데 바이트로 검사 · 배너 줄이 `[AT]` 줄이라
  `continue` 에 먹힘) **셋 다 예외가 아니라 `0건` 으로 조용히 나왔다.**
  숫자가 0 이라 그냥 넘겼으면 **정반대 결론**("가비지 없음 → 주장 기각")을 냈다.
  → **전수를 돌리기 전에 아는 사례 하나가 잡히는지 먼저 본다.** 그 한 줄이 셋을 다 잡는다.
"""
from __future__ import annotations


def z(label: str, n: int, scanned: int, marker: str, unit: str = "건") -> str:
    """계수 한 줄을 규약대로 만든다.

    label   : 사람이 읽는 이름
    n       : 센 값
    scanned : 훑은 줄 수 (분모)
    marker  : 실제로 찾은 문자열/정규식 — **틀린 표지를 잡는 유일한 단서다**
    """
    head = f"{label} {n:,}{unit}"
    if n:
        return head
    why = "🔴 분모가 0 — **관측 자체가 없었다**" if scanned == 0 else "표지가 틀렸는지 먼저 봐라"
    return f"{head}  ⚠ [훑은 줄 {scanned:,} · 찾은 것 {marker!r}] → {why}"


def calib(name: str, found: int, expect_at_least: int = 1) -> str:
    """교정 한 줄 — **전수를 돌리기 전에** 아는 사례가 잡히는지 본다(원장 2.6 · 7.43).

    `garbage_lead.py` 는 이 교정이 없어서 `0건` 을 세 번 연속 보고도 못 알아챘다.
    """
    ok = found >= expect_at_least
    mark = "✅" if ok else "🔴"
    tail = "" if ok else "  ← **전수를 돌리지 마라. 표지부터 고쳐라.**"
    return f"{mark} 교정 `{name}`: 아는 사례 {found}건 (기대 >= {expect_at_least}){tail}"


if __name__ == "__main__":
    print(z("★ 정지 감지", 0, 94860, "★ 정지 감지"))
    print(z("★ 정지 감지", 3, 94860, "★ 정지 감지"))
    print(z("+IPD", 0, 0, "+IPD,"))
    print(calib("배너", 0))
    print(calib("배너", 9))
